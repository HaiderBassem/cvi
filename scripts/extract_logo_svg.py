def build_d(ox, oy, cmds):
    d_parts = []
    for cmd, args in cmds:
        if cmd == "m":
            x = ox + args[0]
            y = PDF_HEIGHT - (oy + args[1])
            d_parts.append(f"M {x:.2f} {y:.2f}")
        elif cmd == "l":
            x = ox + args[0]
            y = PDF_HEIGHT - (oy + args[1])
            d_parts.append(f"L {x:.2f} {y:.2f}")
        elif cmd == "c":
            p1x = ox + args[0]
            p1y = PDF_HEIGHT - (oy + args[1])
            p2x = ox + args[2]
            p2y = PDF_HEIGHT - (oy + args[3])
            p3x = ox + args[4]
            p3y = PDF_HEIGHT - (oy + args[5])
            d_parts.append(f"C {p1x:.2f} {p1y:.2f} {p2x:.2f} {p2y:.2f} {p3x:.2f} {p3y:.2f}")
        elif cmd == "z":
            d_parts.append("Z")
    return " ".join(d_parts)

